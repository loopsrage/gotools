// BuildMultiPagePDF constructs a valid PDF 1.4 binary containing 1..N pages,
// each rendering 36pt Helvetica text via standard PDF Type1 font operators.
func BuildMultiPagePDF(pageTexts []string) []byte {
	if len(pageTexts) == 0 {
		pageTexts = []string{"DEFAULT PAGE"}
	}
	totalObjs := 3 + 2*len(pageTexts)
	offsets := make([]int, totalObjs+1)
	var buf bytes.Buffer
	buf.WriteString("%PDF-1.4\n")

	writeObj := func(id int, body string) {
		offsets[id] = buf.Len()
		fmt.Fprintf(&buf, "%d 0 obj\n%s\nendobj\n", id, body)
	}

	writeObj(1, "<< /Type /Catalog /Pages 2 0 R >>")

	kids := make([]string, len(pageTexts))
	for i := range pageTexts {
		kids[i] = fmt.Sprintf("%d 0 R", 4+2*i)
	}
	writeObj(2, fmt.Sprintf("<< /Type /Pages /Kids [%s] /Count %d >>", strings.Join(kids, " "), len(pageTexts)))
	writeObj(3, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")

	for i, txt := range pageTexts {
		pageObjID := 4 + 2*i
		streamObjID := pageObjID + 1
		escaped := strings.NewReplacer(`\`, `\\`, `(`, `\(`, `)`, `\)`).Replace(txt)
		stream := fmt.Sprintf("BT /F1 36 Tf 72 680 Td (%s) Tj ET", escaped)
		writeObj(pageObjID, fmt.Sprintf(
			"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents %d 0 R >>",
			streamObjID,
		))
		writeObj(streamObjID, fmt.Sprintf("<< /Length %d >>\nstream\n%s\nendstream", len(stream), stream))
	}

	xrefPos := buf.Len()
	fmt.Fprintf(&buf, "xref\n0 %d\n0000000000 65535 f \n", totalObjs+1)
	for id := 1; id <= totalObjs; id++ {
		fmt.Fprintf(&buf, "%010d 00000 n \n", offsets[id])
	}
	fmt.Fprintf(&buf, "trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n", totalObjs+1, xrefPos)
	return buf.Bytes()
}

// RenderBannerPNG renders lines of scaled 5x7 bitmap text onto a white PNG canvas.
func RenderBannerPNG(lines []string, scale int) ([]byte, error) {
	if scale < 4 {
		scale = 6
	}
	maxChars := 1
	for _, l := range lines {
		if len(l) > maxChars {
			maxChars = len(l)
		}
	}
	margin := 32
	charW := 6 * scale
	lineH := 10 * scale
	width := margin*2 + maxChars*charW
	height := margin*2 + len(lines)*lineH

	img := image.NewRGBA(image.Rect(0, 0, width, height))
	draw.Draw(img, img.Bounds(), &image.Uniform{C: color.White}, image.Point{}, draw.Src)

	ink := color.RGBA{R: 0, G: 0, B: 0, A: 255}
	for li, line := range lines {
		upper := strings.ToUpper(line)
		baseY := margin + li*lineH
		for ci, ch := range []rune(upper) {
			rows, ok := glyph5x7[ch]
			if !ok {
				continue
			}
			baseX := margin + ci*charW
			for gy := 0; gy < 7; gy++ {
				rowBits := rows[gy]
				for gx := 0; gx < 5; gx++ {
					if (rowBits & (1 << (4 - gx))) != 0 {
						for dy := 0; dy < scale; dy++ {
							for dx := 0; dx < scale; dx++ {
								img.SetRGBA(baseX+gx*scale+dx, baseY+gy*scale+dy, ink)
							}
						}
					}
				}
			}
		}
	}

	var out bytes.Buffer
	if err := png.Encode(&out, img); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}
